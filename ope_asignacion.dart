void main() {
  double edad = 24; 

  edad +=1; //edad= edad+1
  print("Despues de sumar 1 la edad es: $edad");

  edad -=1; //edad= edad-1
  print("Despues de restar 1 la edad es: $edad");

  edad *=2; //edad= edad*2
  print("Despues de multiplicar por dos la edad es: $edad");

  edad /=2; // edad= edad/2
  print("Despues de dividar entre dos la edad es: $edad");
}