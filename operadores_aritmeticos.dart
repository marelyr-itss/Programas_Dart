void main(){
  //Declaracion de variables y valor
  int num1= 10;
  int num2= 5;

  // Operaciones
  int suma = num1 + num2;

  int resta = num1 - num2;

  int multiplicacion = num1 * num2;

  // División normal
  double divisionNormal = num1 / num2;

  // División entera
  int divisionEntera = num1 ~/ num2; 

  // Residuo    
  int modulo = num1 % num2;              

  // Mostrar resultados
  print("Suma: $suma");
  print("Resta: $resta");
  print("Multiplicación: $multiplicacion");
  print("División normal: $divisionNormal");
  print("División entera: $divisionEntera");
  print("Módulo (residuo): $modulo");
}
